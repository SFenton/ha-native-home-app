import { readFileSync, writeFileSync } from 'node:fs';
import ts from 'typescript';

const file = new URL('../src/shared/composition/expression.ts', import.meta.url);
const source = readFileSync(file, 'utf8');
const parsed = ts.createSourceFile(file.pathname, source, ts.ScriptTarget.Latest, true);
const checker = parsed.statements.find(node => ts.isClassDeclaration(node) && node.name?.text === 'Checker');
if (!checker) throw new Error('Missing canonical Checker');
const canonical = source.slice(checker.getStart(parsed), checker.end);
const selection = 'accountingChecker === this ? checkerAccounting : undefined';
if (canonical.split(selection).length - 1 !== 6) throw new Error('Review the Checker accounting selections before regenerating');
const plain = canonical.replace(/^class Checker /, 'const PlainChecker = class Checker ')
  .replaceAll(selection, 'undefined as typeof checkerAccounting');
const begin = '// BEGIN GENERATED PLAIN CHECKER';
const end = '// END GENERATED PLAIN CHECKER';
const start = source.indexOf(begin), finish = source.indexOf(end);
if (start < 0 || finish < start) throw new Error('Missing generated Checker boundaries');
const block = `${begin}\n// Generated by scripts/generate-expression-checker.mjs; edit the canonical Checker above.\n${plain};\n${end}`;
const generated = source.slice(0, start) + block + source.slice(finish + end.length);
if (process.argv.includes('--check')) {
  if (generated !== source) throw new Error('Stale plain Checker: run npm run generate:expression-checker');
} else if (generated !== source) writeFileSync(file, generated);
